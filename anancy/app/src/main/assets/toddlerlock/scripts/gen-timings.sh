#!/usr/bin/env bash
# Map every clip's real length (and when its ANIMAL word lands) into audio/timings.json.
#
# Why: the playground shows one letter at a time and holds the next one back until the
# current clip has finished. That gate used to be a flat 1300ms guess, but the clips run
# 1.1-2.0s, so letters overlapped. Now the wait is the clip's OWN length, which also means
# the pacing is identical whether the tablet is muted or not.
#
#   "d" = clip length in ms          -> how long to hold the next letter back
#   "w" = animal-word onset in ms    -> when the picture appears ("A" ... "Alligator")
#
# "w" is an estimate: Piper renders "<letter> is for <animal>." with no dependable pause
# between the words (J and N have no internal gap at all), so we take a fixed fraction of
# the SPOKEN span — leading pad and trailing tail measured per clip and excluded. Nudge
# WORD_AT if the picture feels early or late.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/audio/timings.js"
WORD_AT="${WORD_AT:-0.58}"   # fraction into the spoken span where the animal word starts
NOISE="${NOISE:--32dB}"

command -v ffprobe >/dev/null || { echo "need ffprobe" >&2; exit 1; }

first=1
{
  # NOT .json on purpose: the Android WebView serves this page from file://, where fetch()
  # is blocked by the opaque origin. A <script> tag loads fine from anywhere, so the map is
  # a plain assignment that index.html pulls in before app.js.
  echo "// Generated by scripts/gen-timings.sh -- do not edit by hand."
  echo "// <voice>: { <key>: [clip ms, animal-word ms] }"
  echo "window.__tlTimings = {"
  for vdir in "$ROOT"/audio/*/; do
    v="$(basename "$vdir")"
    [ -f "$vdir/A.wav" ] || continue
    [ $first -eq 1 ] || echo ","
    first=0
    printf '  "%s": {' "$v"
    sep=""
    for f in "$vdir"*.wav; do
      key="$(basename "$f" .wav)"
      dur="$(ffprobe -v error -show_entries format=duration -of csv=p=0 "$f")"
      # leading pad = first silence_end; trailing tail = last silence_start
      sil="$(ffmpeg -v info -i "$f" -af "silencedetect=noise=$NOISE:d=0.05" -f null - 2>&1 \
             | grep -oP 'silence_(start|end): [0-9.]+' || true)"
      s0="$(printf '%s\n' "$sil" | grep -m1 'silence_end' | grep -oP '[0-9.]+$' || true)"
      s1="$(printf '%s\n' "$sil" | grep 'silence_start' | tail -1 | grep -oP '[0-9.]+$' || true)"
      [ -n "$s0" ] || s0=0
      # a leading silence_start of 0 is the pad; a trailing one must be after s0 to count
      if [ -z "$s1" ] || awk "BEGIN{exit !($s1 <= $s0)}"; then s1="$dur"; fi
      read -r d w < <(awk -v d="$dur" -v a="$s0" -v b="$s1" -v r="$WORD_AT" \
        'BEGIN{printf "%d %d\n", d*1000+0.5, (a+(b-a)*r)*1000+0.5}')
      printf '%s"%s":[%s,%s]' "$sep" "$key" "$d" "$w"
      sep=","
    done
    printf '}'
  done
  echo
  echo "};"
} > "$OUT"

echo "wrote $OUT"

# Same story for the voice list: audio/voices.json is fetched, and fetch() is refused from a
# file:// origin, so on the Android kiosk it never arrived -- the voice picker came up empty
# and the playground fell back to a hardcoded default whatever you'd chosen. Mirror it into a
# <script> assignment the WebView can actually load. voices.json stays the source of truth.
VJS="$ROOT/audio/voices.js"
if [ -f "$ROOT/audio/voices.json" ]; then
  {
    echo "// Generated by scripts/gen-timings.sh from audio/voices.json -- do not edit by hand."
    printf 'window.__tlVoices = '
    cat "$ROOT/audio/voices.json"
    echo ";"
  } > "$VJS"
  echo "wrote $VJS"
else
  echo "no audio/voices.json -- skipped $VJS" >&2
fi
